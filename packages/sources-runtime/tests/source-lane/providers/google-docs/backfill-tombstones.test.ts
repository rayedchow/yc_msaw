/**
 * Coordinator-applied shared patches requested by the google-docs lane
 * (patch-requests/google-docs.md 1 + 2), exercised through production code on the real migration plan.
 */
const TENANT = "tenant-backfill-tombstones";
const DOC = "doc-bt-1";

async function insertTab(revision: string, tabId: string, title: string, body: string, capturedAt: string): Promise<void> {
  await query(
    `INSERT INTO google_doc_tab_snapshots (user_id, doc_id, tab_id, revision_id, title, content, content_sha, captured_at)
     VALUES ($1, $2, $3, $4, $5, $6::jsonb, $7, $8)`,
    [TENANT, DOC, tabId, revision, title, JSON.stringify({ content: body, suggestions: [], suggestionsAccessible: true }), `sha-${revision}-${tabId}`, capturedAt],
  );
}

/** Mirror files of the doc itself (directory indexes are regenerated by every backfill and are not doc content). */
async function docMirrorPaths(): Promise<string[]> {
  return (await query<{ path: string }>(`SELECT path FROM mirror_files WHERE user_id = $1 ORDER BY path`, [TENANT]))
    .map((r) => r.path)
    .filter((p) => p.startsWith("sources/google-docs/") && !p.endsWith("/index.md") && p !== "sources/google-docs/index.md");
}

describe("mirror backfill honours later revisions and lifecycle tombstones (google-docs request 1)", () => {
  beforeAll(async () => {
    await ready;
  });
  beforeEach(async () => {
    await resetTenant(TENANT);
    await query(`DELETE FROM document_summaries WHERE user_id = $1`, [TENANT]);
    await query(`DELETE FROM gdocs_file_checkpoints WHERE tenant_id = $1`, [TENANT]);
  });

  it("does not resurrect a tab deleted in a later revision", async () => {
    await insertTab("r1", "t.0", "Main", "main body v1", "2026-10-01T10:00:00Z");
    await insertTab("r1", "t.1", "Appendix", "APPENDIX-ONLY-IN-R1", "2026-10-01T10:00:00Z");
    await insertTab("r2", "t.0", "Main", "main body v2", "2026-10-02T10:00:00Z");
    await query(`INSERT INTO document_summaries (user_id, doc_id, title, overview) VALUES ($1, $2, 'Plan', 'overview')`, [TENANT, DOC]);

    const result = await backfillSourceWikiMirror({ userId: TENANT, sources: ["google-docs"] });
    expect(result.googleDocs.rows).toBe(1);
    const rows = await query<{ path: string; content: string }>(`SELECT path, content FROM mirror_files WHERE user_id = $1`, [TENANT]);
    expect(rows.length).toBeGreaterThan(0);
    const all = rows.map((r) => r.content).join("\n");
    expect(all).toContain("main body v2");
    expect(all).not.toContain("APPENDIX-ONLY-IN-R1");
    expect(all).not.toContain("main body v1");
  });

  it("does not re-materialize a trashed doc", async () => {
    await insertTab("r1", "t.0", "Main", "main body", "2026-10-01T10:00:00Z");
    await query(`INSERT INTO document_summaries (user_id, doc_id, title, overview) VALUES ($1, $2, 'Plan', 'overview')`, [TENANT, DOC]);
    await backfillSourceWikiMirror({ userId: TENANT, sources: ["google-docs"] });
    expect((await docMirrorPaths()).length).toBeGreaterThan(0);

    await transitionLifecycle(TENANT, DOC, "trashed", { mailbox: "ada@corp.example" });
    await query(`DELETE FROM mirror_files WHERE user_id = $1`, [TENANT]);
    const again = await backfillSourceWikiMirror({ userId: TENANT, sources: ["google-docs"] });
    expect(again.googleDocs.rows).toBe(0);
    expect(await docMirrorPaths()).toEqual([]);

    // Restore brings it back.
    await transitionLifecycle(TENANT, DOC, "active", { mailbox: "ada@corp.example" });
    await backfillSourceWikiMirror({ userId: TENANT, sources: ["google-docs"] });
    expect((await docMirrorPaths()).length).toBeGreaterThan(0);
  });
});

